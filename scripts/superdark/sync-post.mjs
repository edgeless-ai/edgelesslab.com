import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const markdown = readFileSync(resolve(root, 'content/blog/superdark-factory.md'), 'utf8');
const [, header, body] = markdown.split(/^---\s*$/m);
if (!header || !body) throw new Error('Missing frontmatter or article body');
const metadata = Object.fromEntries(header.trim().split('\n').map(line => {
  const match = line.match(/^(\w+): (.+)$/);
  if (!match) throw new Error(`Unsupported frontmatter: ${line}`);
  const [, key, raw] = match;
  let value;
  try { value = JSON.parse(raw); } catch { value = raw; }
  return [key, value];
}));
const content = body.trim();
const text = '// Generated by node scripts/superdark/sync-post.mjs from content/blog/superdark-factory.md.\nimport type { BlogPost } from "./blog-types";\n\nexport const superdarkFactoryPost: BlogPost = '+JSON.stringify({...metadata,content},null,2)+';\n';
const target = resolve(root,'src/lib/blog-superdark-factory.ts');
if (process.argv.includes('--check')) {
  if (readFileSync(target,'utf8')!==text) throw new Error('Blog registry and markdown have drifted; run sync-post.mjs');
  console.log('Superdark markdown and TypeScript registry match.');
} else { writeFileSync(target,text); console.log('Synced Superdark registry.'); }
